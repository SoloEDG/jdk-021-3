import type { Game, TableOrder } from "./types";
import { zeroIngredients } from "./inventory";

function table(
  id: number,
  name: string,
  arrival: number,
  windowStart: number,
  windowEnd: number,
  early: number,
  patience: number,
  recipes: TableOrder["slots"],
  quote: number,
  nextSlot: number,
): TableOrder {
  return {
    id,
    name,
    arrival,
    early,
    windowStart,
    windowEnd,
    slots: recipes.map((r) => ({ ...r, id: nextSlot++ })),
    quote,
    patience,
    reserveEnabled: true,
    reserved: zeroIngredients(),
    status: "scheduled",
    seatedAt: null,
    deadline: null,
    penaltyBooked: false,
    servedAt: null,
    score: null,
    paid: null,
    note: "预约已确认，开餐前可调整到店时间、菜单和整桌报价。",
  };
}

